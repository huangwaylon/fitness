EXACT = dict(E)  # later add() overrides earlier for identical keys
E = [e for _, e in sorted(enumerate(E), key=lambda ie: (-len(ie[1][0]), -ie[0]))]  # longest first; later wins ties

ONECHAR = set('餅鯛鮭鱈鰤鯖鯵鰯鮎鯉鮒蛸麩栗柿梨桃卵豚牛鶏葱芋蕪筍鰹鰻鱧鰆蜆蛤牡蠣')

def match(name):
    n = norm(name)
    n = re.sub(r'【[^】]*】|\[[^\]]*\]|<[^>]*>|≪[^≫]*≫|《[^》]*》', ' ', n).strip()
    n = re.sub(r'^[・\-\s※◎○●☆★]+', '', n)
    full = re.sub(r'\s+', '', n)
    base = re.sub(r'[(（][^)）]*[)）]', '', full)
    for cand in (full, base):
        if cand in EXACT:
            return EXACT[cand]
    # substring: longest key contained in base, then in full
    for cand in (base, full):
        for k, v in E:
            if k in cand and (len(k) >= 2 or cand == k or k in ONECHAR):
                return v
    return None


FRAC = {'½': '1/2', '⅓': '1/3', '¼': '1/4', '⅔': '2/3', '¾': '3/4'}

def _num(s):
    """parse '1と1/2', '1/2', '1.5', '2~3' -> float"""
    s = s.strip()
    for a, b in FRAC.items():
        s = s.replace(a, b)
    m = re.match(r'^(\d+(?:\.\d+)?)\s*[~〜～\-ー]\s*(\d+(?:\.\d+)?)', s)
    if m:
        return (float(m.group(1)) + float(m.group(2))) / 2
    m = re.match(r'^(\d+)\s*と\s*(\d+)\s*/\s*(\d+)', s)
    if m:
        return int(m.group(1)) + int(m.group(2)) / int(m.group(3))
    m = re.match(r'^(\d+)\s*/\s*(\d+)', s)
    if m:
        return int(m.group(1)) / int(m.group(2))
    m = re.match(r'^(\d+(?:\.\d+)?)', s)
    if m:
        return float(m.group(1))
    if s.startswith('半'):
        return 0.5
    return None

UNIT_RE = r'(大さじ|小さじ|カップ|かっぷ|合|升|kg|g|ml|cc|l|リットル|りっとる|人分|人前|尾分|羽分|半身|身|ぱい|板|櫛|本|個|枚|丁|尾|匹|片|かけ|束|把|わ|袋|玉|株|房|切れ|切|膳|杯|はい|腹|節|粒|缶|パック|ぱっく|cm|m|羽|連|さく|冊|さや|輪|帖|箱|つまみ|つ|包|節|茶碗)'

def grams(text, ent):
    """Return grams (float), 0.0 for negligible/適量, None if unknown."""
    t = re.sub(r'(\d)\s+(\d+\s*/\s*\d+)', r'\1と\2', norm(text)).replace('・', 'と')
    t = t.lower().replace('ｇ', 'g').replace('ℓ', 'l').replace(',', '')
    t = t.replace('ｃｃ', 'cc')
    t = re.sub(r'\s+', '', t)
    t = t.replace('グラム', 'g').replace('ぐらむ', 'g').replace('キロ', 'kg').replace('ミリリットル', 'ml')
    t = re.sub(r'軽く|山盛り|すりきり|弱|強|程度|ほど|程|くらい|位|ぐらい|前後', '', t)
    for kj, ar in (('一', '1'), ('二', '2'), ('三', '3'), ('四', '4'), ('五', '5'), ('六', '6'), ('七', '7'), ('八', '8'), ('九', '9'), ('十', '10')):
        t = re.sub(kj + r'(?=[片本個枚尾匹束つ切合升杯])', ar, t)
    m_egg = re.search(r'卵(\d+)個分', t)
    if m_egg:
        return float(m_egg.group(1)) * 50
    t = re.sub(r'(\d)[こけヶ](?![a-zぁ-ん])', r'\1個', t).replace('莢', 'さや')
    if t in ('半分', '半量'):
        return 0.5 * (ent['pcs'].get('個') or 0) if ent and ent['pcs'].get('個') else None
    if re.search(r'\d+(?:\.\d+)?cm厚', t) and not re.search(r'\d\s*k?g(?![a-z])', t):
        return None   # '大根3cm厚さ 8個': slices, not whole pieces
    t = re.sub(r'\d+(?:\.\d+)?mm厚?|厚さ\d+(?:\.\d+)?(?:mm|cm)の?(?:もの)?|\d+cm角|長さ\d+cm', '', t)
    t = t.replace('コ', '個').replace('一握り', 'ひとにぎり').replace('一掴み', 'ひとつかみ').replace('ケ', '個').replace('ヶ', '個')
    t = t.replace('ふたつまみ', '2つまみ').replace('数本', '3本').replace('数枚', '3枚').replace('数個', '3個').replace('数切れ', '3切れ')
    if not t:
        return None
    if re.search(r'適量|適宜|適時|少量|少々|お好み|好みで|好み|このみ|好き|ひたひた|各適|ひとつまみ|ひとつかみ|少し|ひとふり|ひと振り|お好きな|適当|ひとにぎり|一つまみ|ひとかけ|多め|たっぷり', t) and not re.search(r'\d', t):
        if 'ひとつまみ' in t or '一つまみ' in t:
            return 1.0
        if 'ひとかけ' in t:
            return 15.0
        if 'ひとにぎり' in t or 'ひとつかみ' in t:
            return 30.0 if ent and ent['kind'] not in ('salt', 'sugar', 'powder', 'flake') else 2.0
        if '少々' in t or '少量' in t or 'ひとふり' in t:
            return 0.5
        return 0.0
    # a count and the weight of one: '16枚(1枚30g)', '4本(1本/約250~350g)' -> 16 x 30, 4 x 300
    m = re.match(r'^(\d[\d./と]*)([^\d()]{1,4})\(1\2/?(?:約)?(\d+(?:\.\d+)?)(?:[~〜～](\d+(?:\.\d+)?))?(kg|g)\)', t)
    if m and _num(m.group(1)) is not None:
        one = (float(m.group(3)) + float(m.group(4) or m.group(3))) / 2 * (1000 if m.group(5) == 'kg' else 1)
        return _num(m.group(1)) * one
    # explicit grams anywhere (e.g. '2枚(100g)', '1/2本(約80g)'; a range '250~350g' -> its middle)
    m = re.search(r'(?:約)?(\d+(?:\.\d+)?)(?:[~〜～](\d+(?:\.\d+)?))?\s*(kg|g)(?![a-z])', t)
    if m and not re.match(r'^\d+(?:\.\d+)?(?:ml|cc|l)', t):
        v = (float(m.group(1)) + float(m.group(2) or m.group(1))) / 2 * (1000 if m.group(3) == 'kg' else 1)
        mm = re.search(r'(\d+(?:\.\d+)?)\s*g\s*[x×]\s*(\d+)', t)
        if mm:
            v = float(mm.group(1)) * float(mm.group(2))
        return v
    kind = KIND[ent['kind']] if ent else KIND['solid']
    pcs = ent['pcs'] if ent else {}
    # combined measures like '1カップ大さじ2' / '大さじ1小さじ1'
    toks = re.findall(r'(\d[\d./と]*)(カップ|かっぷ)|(カップ|かっぷ|大さじ|小さじ)(\d[\d./と]*)', t)
    if len(toks) >= 2:
        tot = 0.0
        for a, u1, u2, b in toks:
            u = u1 or u2; n = _num(a or b)
            if n is None: return None
            tot += n * (kind[2] if u in ('カップ', 'かっぷ') else kind[0] if u == '大さじ' else kind[1])
        return tot
    # spoon / cup with number after: 大さじ1と1/2, カップ2
    m = re.search(r'(大さじ|小さじ|カップ|かっぷ|大|小)(\d[\d./と~〜～]*|半|½)', t)
    if m and (m.group(1) not in ('大', '小') or not re.search(r'[本個枚尾匹玉株]', t)):
        n = _num(m.group(2))
        if n is not None:
            u = m.group(1)
            per = kind[0] if u in ('大さじ', '大') else kind[1] if u in ('小さじ', '小') else kind[2]
            extra = 0
            m2 = re.search(r'(大さじ|小さじ)(\d[\d./と]*)$', t[m.end():])
            if m2 and u in ('カップ', 'かっぷ'):
                n2 = _num(m2.group(2)); extra = (n2 or 0) * (kind[0] if m2.group(1) == '大さじ' else kind[1])
            return n * per + extra
    # number + unit
    m = re.search(r'(?:約|中|大|小|大玉|小玉|中玉|特大)?(\d[\d./と~〜～-]*|半)\s*' + UNIT_RE, t)
    if m:
        n = _num(m.group(1))
        u = m.group(2)
        size = 1.0
        pre = t[:m.start(1)]
        if pre.endswith('大') or pre.endswith('大玉'): size = 1.3
        elif pre.endswith('小') or pre.endswith('小玉'): size = 0.7
        if n is None:
            return None
        if u in ('kg',): return n * 1000
        if u == 'g': return n
        if u in ('ml', 'cc'): return n * kind[3] if kind[3] else n
        if u in ('l', 'リットル', 'りっとる'): return n * 1000 * (kind[3] or 1)
        if u in ('カップ', 'かっぷ'): return n * kind[2]
        if u in ('大さじ',): return n * kind[0]
        if u in ('小さじ',): return n * kind[1]
        if u in ('合', '升'):
            if u in pcs: return n * pcs[u]
            return n * (180 if u == '合' else 1800) * (kind[3] or 1)
        if u == 'つまみ': return n * (pcs.get('つまみ', 1.0))
        if u in ('膳', '茶碗', '杯', '人分', '人前') and ent and ent['id'] == '01088':
            return n * 150
        if u in ('人分', '人前'):
            return n * pcs['人前'] if '人前' in pcs else None
        if u in pcs: return n * pcs[u] * size
        alias = {'切': '切れ', '切れ': '切', 'かけ': '片', '片': 'かけ', '把': '束', '束': '把', 'はい': '杯', '杯': 'はい', '尾': '匹', '匹': '尾',
                 '冊': 'さく', 'さく': '冊', 'わ': '束', 'つ': '個', '玉': '個', '個': '玉', '株': '個', 'ぱっく': 'パック', '包': 'パック'}
        if alias.get(u) in pcs: return n * pcs[alias[u]] * size
        return None
    # bare number (assume grams if > 5)
    m = re.fullmatch(r'(\d+(?:\.\d+)?|\d+/\d+|\d+と\d+/\d+)', t)
    if m:
        n = _num(m.group(1))
        for u in ('個', '本', '玉', '枚'):
            if u in pcs and n is not None and n < 10:
                return n * pcs[u]
        if n is not None and n >= 5:
            return n
    return None

