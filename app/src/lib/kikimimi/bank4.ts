// ききみみ クイズ level 4 「かわ・もり」 (B1+ → B2; docs/curriculum.md "Modes" increment 1): real daily life in island
// clothes. Each item is cut from a scenario seed (§5.5: setting × goal × complication) with a register, speech
// conditions and a pragmatic layer (`tags`), written for an adult learner whose listening is already good: natural
// speed, reductions, indirect answers, self-corrections, understatement and sarcasm. Never childish: real places and
// money (yen, dollars), villagers playing people. American English: US vocabulary, idiom, spelling and social norms
// (tipping, small talk), Tokyo daily life beside American life.
//   `en` is what's shown at the reveal (US spelling); `tts` is what's spoken
// when that differs (§9: gonna, lemme, d'you; every number written out). `note` is the trap in Japanese (≤ 40 字).
//   Types: `reply` (TOEIC Part 2, the right reply often indirect; traps repeat a word or a sound, or answer another
// question), `mean` (what do they really mean: the literal reading, the opposite and a plausible wrong inference as
// distractors), `word` (reductions and contractions in context, 3 choices that all fit), `num` (natural-speed numbers
// in real contexts, the distractors the corrected value, a heard number or a plausible sum). No `pic`: the art is
// island things, and these scenes aren't.
//   Voices: one US cast voice per villager for good (cast.ts CAST: accent, gender, slot; 12 US voices, 6 a gender),
// for the neural TTS (scripts/tts/cast.json); UK and AU (EXPOSURE) only on the やま/ほし accent-exposure items.
import type { RosterId } from '#lib/villagers/roster.ts';
import type { Item, ItemType, Tags } from './bank.ts';
import { MEAN_ASK, single, tg } from './content/build.ts';
import { staged } from './staging.ts';

type Extra = { tts?: string; focus?: string; ask?: string };
type Row = readonly [id: string, speaker: RosterId, en: string, ja: string, note: string, choices: readonly string[], tags: Tags, extra?: Extra];

const item = (type: ItemType) => ([id, speaker, en, ja, note, choices, tags, x = {}]: Row): Item => {
  const focus = type === 'word' ? choices[0] : x.focus;
  const ask = x.ask ?? (type === 'mean' ? MEAN_ASK : undefined);
  return {
    ...single(4, type, id, speaker, en, ja, note, choices, tags),
    ...(x.tts && { tts: x.tts }), ...(focus && { focus }), ...(ask && { ask }), ...staged(id), ...HELP[id]
  };
};

