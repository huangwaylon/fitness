// `npm run gas:build`: bundle app/gas/main.ts (+ the parser) into app/apps-script/Code.js, one plain global script
// for the Apps Script editor (or `clasp push`). Apps Script only calls top-level functions, so the IIFE bundle is
// followed by a top-level `function doPost(e)` that forwards to it.
import { buildSync } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = (p: string) => fileURLToPath(new URL(p, import.meta.url));
export const OUT_FILE = here('../apps-script/Code.js');

const BANNER = `// GENERATED by \`npm run gas:build\` from app/gas/main.ts and app/src/lib/ingest/parse.ts. Do not edit here.
// Island Fund web app (ADR 0015). Setup: docs/ops/google-setup.md.`;

const FOOTER = `
/** Apps Script entry point. There is deliberately no doGet. */
function doPost(e) {
  return IslandFund.doPost(e);
}
`;

export function bundle(): string {
  const r = buildSync({
    entryPoints: [here('./main.ts')],
    bundle: true,
    write: false,
    format: 'iife',
    globalName: 'IslandFund',
    platform: 'neutral',
    target: 'es2019', // Apps Script V8 is modern, but stay conservative
    charset: 'utf8',
    legalComments: 'none',
    tsconfigRaw: {}, // the app tsconfig extends SvelteKit's generated one, irrelevant here
    banner: { js: BANNER },
    footer: { js: FOOTER }
  });
  return r.outputFiles[0].text;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const code = bundle();
  writeFileSync(OUT_FILE, code);
  console.log(`wrote ${OUT_FILE} (${(Buffer.byteLength(code) / 1024).toFixed(1)} KB)`);
}
