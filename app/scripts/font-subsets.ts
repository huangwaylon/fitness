// Trim Zen Maru Gothic to the unicode-range slices the app can show (round 5 P6: the full @fontsource CSS was
// 250 @font-face rules, ~200 KB of render-blocking CSS). Keeps every slice that holds a character used anywhere
// in src/ (catalogs, place / workout / villager names) plus all kana, Latin and full-width forms, woff2 only.
// Kanji typed by a user outside these slices fall back to the system rounded font.
// Usage (from app/): npm run fonts:subset   → src/lib/styles/fonts.css (commit it). src/lib/styles/fonts.test.ts checks
// that every character in src/ is still covered, so re-run this after adding copy with new kanji.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const APP = join(import.meta.dirname, '..');
export const PKG = join(APP, 'node_modules', '@fontsource', 'zen-maru-gothic');
const OUT = join(APP, 'src', 'lib', 'styles', 'fonts.css');
const WEIGHTS = [500, 700];

function walk(dir: string, out: string[] = []): string[] {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) {
      if (f !== 'fixtures') walk(p, out);
    } else if (/\.(svelte|ts|json)$/.test(f) && !/\.test\.ts$/.test(f)) out.push(p);
  }
  return out;
}

export function parseRanges(range: string): [number, number][] {
  return range.split(',').map((r) => {
    const [a, b] = r.trim().replace(/^U\+/i, '').split('-');
    return [parseInt(a, 16), parseInt(b ?? a, 16)];
  });
}

export const covers = (ranges: [number, number][], cp: number) => ranges.some(([a, b]) => cp >= a && cp <= b);

/** Code points that must render in Zen Maru Gothic (also used by fonts.test.ts). */
export function wanted(): Set<number> {
  const cps = new Set<number>();
  for (const f of walk(join(APP, 'src'))) {
    // Code and copy only: comments are full of kanji nobody sees.
    const text = readFileSync(f, 'utf8').replace(/\/\*[\s\S]*?\*\/|<!--[\s\S]*?-->|(^|[^:'"`\\])\/\/[^\n]*/g, '$1');
    for (const ch of text) cps.add(ch.codePointAt(0)!);
  }
  for (let cp = 0x3040; cp <= 0x30ff; cp++) cps.add(cp); // all kana (typed villager names)
  return cps;
}

function main() {
  const need = wanted();
  const blocks: string[] = [];
  for (const w of WEIGHTS) {
    const css = readFileSync(join(PKG, `${w}.css`), 'utf8');
    for (const m of css.matchAll(/@font-face\s*{[^}]*}/g)) {
      const block = m[0];
      const range = /unicode-range:\s*([^;]+);/.exec(block)?.[1];
      if (!range) continue;
      const ranges = parseRanges(range);
      // Latin and full-width forms always; otherwise only slices with a character we use.
      const keep = covers(ranges, 0x41) || covers(ranges, 0xff01) || [...need].some((cp) => cp > 0x7f && covers(ranges, cp));
      if (!keep) continue;
      const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(block)?.[1];
      if (!file) continue;
      const url = relative(join(APP, 'src', 'lib', 'styles'), join(PKG, 'files', file));
      blocks.push(block.replace(/src:[^;]+;/, `src: url(${url}) format('woff2');`));
    }
  }
  writeFileSync(OUT, `/* Generated by scripts/font-subsets.ts: Zen Maru Gothic ${WEIGHTS.join(' + ')}, only the slices the app uses. */\n${blocks.join('\n')}\n`);
  console.log(`fonts.css: ${blocks.length} @font-face rules`);
}

if (import.meta.main ?? process.argv[1]?.endsWith('font-subsets.ts')) main();
