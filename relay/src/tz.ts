export function tzOf(lat: number, lng: number): string {
  for (const [s, w, n, e, tz] of BOXES) if (lat >= s && lat <= n && lng >= w && lng <= e) return tz;
  const h = Math.round(lng / 15);
  return h === 0 ? 'Etc/GMT' : `Etc/GMT${h > 0 ? '-' : '+'}${Math.abs(h)}`;
}
